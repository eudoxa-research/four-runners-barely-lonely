// Exact ML of a 2-dim subtorus of (R/Z)^4 given 4 forms (s_i, r_i); same candidate set as torusml.c
// ((a) three signed branches equal, (b) two proportional forms at a common level and a third at a
// half-integer, (c) two independent forms at half-integers), but the integer offsets of a base pair of
// independent forms are enumerated only over a fundamental domain of Z^2 / M Z^2 (|det M| classes).
// Input lines: s1 r1 s2 r2 s3 r3 s4 r4 ; output: p q X Y Den  (ML = p/q, witness (X/Den, Y/Den)).
#include <stdio.h>
#include <stdlib.h>
typedef long long ll;
typedef __int128 i128;
static ll gcdll(ll a, ll b){ if(a<0)a=-a; if(b<0)b=-b; while(b){ll t=a%b;a=b;b=t;} return a; }
static ll mod(ll a, ll m){ ll r=a%m; if(r<0) r+=m; return r; }
static ll fl(ll a, ll b){ /* floor(a/b), b>0 */ ll q=a/b; if((a%b)!=0 && ((a<0)!=(b<0))) q--; return q; }
static int ns[4], nr[4];
static ll bp, bq, bX, bY, bDen;
// evaluate G at (X/Den, Y/Den) and update best
static void consider(ll X, ll Y, ll Den){
    if(Den<0){ Den=-Den; X=-X; Y=-Y; }
    X=mod(X,Den); Y=mod(Y,Den);
    ll best=Den;
    for(int i=0;i<4;i++){ ll z=mod((ll)ns[i]*X+(ll)nr[i]*Y, Den); if(Den-z<z) z=Den-z; if(z<best) best=z; }
    if((i128)best*bq > (i128)bp*Den){ ll g=gcdll(best,Den); bp=best/g; bq=Den/g; bX=X; bY=Y; bDen=Den; }
}
// fundamental domain reps of Z^2 / L, L generated by columns (Si,Sj),(Ri,Rj) of M=[[Si,Ri],[Sj,Rj]] (rows = forms)
// returns g1,g2 such that reps are (a,b), 0<=a<g1, 0<=b<g2 ; valid because L = <(g1,c),(0,g2)>.
static void hnf2(ll Si, ll Ri, ll Sj, ll Rj, ll *g1, ll *g2){
    ll D = Si*Rj - Ri*Sj; ll a=gcdll(Si,Ri); *g1=a; *g2 = (D<0?-D:D)/a;
}
int main(){
    while(scanf("%d %d %d %d %d %d %d %d",&ns[0],&nr[0],&ns[1],&nr[1],&ns[2],&nr[2],&ns[3],&nr[3])==8){
        bp=0; bq=1; bX=0; bY=0; bDen=1;
        // (c) two independent forms at half-integers: l_i = a + 1/2, l_j = b + 1/2
        for(int i=0;i<4;i++) for(int j=i+1;j<4;j++){
            ll D=(ll)ns[i]*nr[j]-(ll)nr[i]*ns[j]; if(D==0) continue;
            ll g1,g2; hnf2(ns[i],nr[i],ns[j],nr[j],&g1,&g2);
            for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                // solve [[Si,Ri],[Sj,Rj]] (x,y) = (a+1/2, b+1/2) -> over 2D
                ll ui=2*a+1, uj=2*b+1;
                ll X = ui*nr[j] - uj*nr[i], Y = ns[i]*uj - ns[j]*ui; consider(X, Y, 2*D);
            }
        }
        // (a) base pair (i,j) independent, third m, signs: l_i = a + si t, l_j = b + sj t, l_m = k + sm t, t in (0,1/2]
        for(int i=0;i<4;i++) for(int j=i+1;j<4;j++) for(int m=0;m<4;m++){
            if(m==i||m==j) continue;
            // use each unordered triple once: require that (i,j) is the first independent pair of the sorted triple
            int tr[3]={i,j,m}; // sort
            for(int x=0;x<3;x++) for(int y=x+1;y<3;y++) if(tr[y]<tr[x]){int t=tr[x];tr[x]=tr[y];tr[y]=t;}
            int fi=-1,fj=-1;
            for(int x=0;x<3 && fi<0;x++) for(int y=x+1;y<3;y++){ ll d=(ll)ns[tr[x]]*nr[tr[y]]-(ll)nr[tr[x]]*ns[tr[y]]; if(d!=0){fi=tr[x];fj=tr[y];break;} }
            if(fi!=i || fj!=j) continue;
            ll D=(ll)ns[i]*nr[j]-(ll)nr[i]*ns[j];
            ll g1,g2; hnf2(ns[i],nr[i],ns[j],nr[j],&g1,&g2);
            for(int si=-1;si<=1;si+=2) for(int sj=-1;sj<=1;sj+=2) for(int sm=-1;sm<=1;sm+=2){
                // s(t) = Minv (a + si t, b + sj t); Minv = (1/D) [[Rj, -Ri],[-Sj, Si]]
                // l_m(s) = (1/D) [ (Sm Rj - Rm Sj)(a + si t) + (-Sm Ri + Rm Si)(b + sj t) ] = (P0 + t Q0)/D
                ll cA = (ll)ns[m]*nr[j] - (ll)nr[m]*ns[j], cB = -(ll)ns[m]*nr[i] + (ll)nr[m]*ns[i];
                ll Q0 = cA*si + cB*sj;          // l_m slope numerator (over D)
                ll den = Q0 - (ll)sm*D;         // equation: (P0 + t Q0)/D = k + sm t  ->  t (Q0 - sm D) = k D - P0
                if(den==0) continue;
                for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                    ll P0 = cA*a + cB*b;
                    // t = (k D - P0)/den in (0, 1/2]  ->  k D - P0 in (0, den/2] (den>0) or [den/2, 0) (den<0)
                    ll lo, hi; // range for N = k*D - P0 (scaled by 2 for the half)
                    // solve for k: if den>0: 0 < kD - P0 <= den/2 ; if den<0: den/2 <= kD - P0 < 0
                    ll A_, B_; // N in (A_, B_] in units of 1/2: use 2N
                    if(den>0){ A_=0; B_=den; } else { A_=den; B_=0; }  // 2N in (A_*?, ...]: handle below
                    // 2(kD - P0) in (0, den] if den>0 ; in [den, 0) if den<0
                    ll Dabs = D>0?D:-D;
                    // iterate k over the range: kD in (P0, P0 + den/2] or [P0 + den/2, P0)
                    ll L2 = 2*P0 + (den>0?0:den), H2 = 2*P0 + (den>0?den:0); // 2kD in (L2,H2] or [L2,H2)
                    ll kmin, kmax;
                    if(D>0){ kmin = fl(L2, 2*D) - 1; kmax = fl(H2, 2*D) + 1; } else { kmin = fl(-H2, -2*D) - 1; kmax = fl(-L2, -2*D) + 1; }
                    (void)lo;(void)hi;(void)A_;(void)B_;(void)Dabs;
                    for(ll k=kmin;k<=kmax;k++){
                        ll N = k*D - P0;
                        // check t = N/den in (0, 1/2]
                        if(den>0){ if(!(N>0 && 2*N<=den)) continue; } else { if(!(N<0 && 2*N>=den)) continue; }
                        // prune: t <= current best cannot improve (G(s) <= t on active forms)
                        // t = N/den ; compare N/den <= bp/bq
                        { i128 lhs=(i128)(N<0?-N:N)*bq, rhs=(i128)bp*(den<0?-den:den); if(lhs<=rhs) continue; }
                        // s = Minv (a + si t, b + sj t) with t = N/den: common denominator D*den
                        ll ui = a*den + si*N, uj = b*den + sj*N;   // (a + si t)*den
                        ll X = (ll)nr[j]*ui - (ll)nr[i]*uj, Y = -(ll)ns[j]*ui + (ll)ns[i]*uj;
                        consider(X, Y, D*den);
                    }
                }
            }
        }
        // (b) proportional pair (i,j) at common level, third m at half-integer; base pair (i,m) independent
        for(int i=0;i<4;i++) for(int j=0;j<4;j++){
            if(i==j) continue;
            if((ll)ns[i]*nr[j] != (ll)ns[j]*nr[i]) continue;
            if(i>j) continue;
            for(int m=0;m<4;m++){ if(m==i||m==j) continue;
                ll D=(ll)ns[i]*nr[m]-(ll)nr[i]*ns[m]; if(D==0) continue;
                ll g1,g2; hnf2(ns[i],nr[i],ns[m],nr[m],&g1,&g2);
                for(int si=-1;si<=1;si+=2) for(int sj=-1;sj<=1;sj+=2){
                    // l_i = a + si t, l_m = b + 1/2 ; l_j(s) = (cA (a + si t) + cB (b + 1/2))/D ; equation l_j = k + sj t
                    ll cA = (ll)ns[j]*nr[m] - (ll)nr[j]*ns[m], cB = -(ll)ns[j]*nr[i] + (ll)nr[j]*ns[i];
                    ll Q0 = cA*si; ll den = Q0 - (ll)sj*D; if(den==0) continue;
                    for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                        // 2 P0 = 2 cA a + cB (2b+1)
                        ll P2 = 2*cA*a + cB*(2*b+1);
                        // t = (k D - P0)/den = (2kD - P2)/(2 den)
                        ll den2=2*den;
                        ll L2 = P2 + (den2>0?0:den2/2*1), H2 = P2 + (den2>0?den2/2:0);
                        // 2kD in (P2, P2 + den] or [P2 + den, P2)
                        ll lo2 = (den>0)? P2 : P2+den, hi2 = (den>0)? P2+den : P2;
                        ll kmin, kmax;
                        if(D>0){ kmin=fl(lo2,2*D)-1; kmax=fl(hi2,2*D)+1; } else { kmin=fl(-hi2,-2*D)-1; kmax=fl(-lo2,-2*D)+1; }
                        (void)L2;(void)H2;
                        for(ll k=kmin;k<=kmax;k++){
                            ll N2 = 2*k*D - P2; // t = N2/den2
                            if(den2>0){ if(!(N2>0 && 2*N2<=den2)) continue; } else { if(!(N2<0 && 2*N2>=den2)) continue; }
                            { i128 lhs=(i128)(N2<0?-N2:N2)*bq, rhs=(i128)bp*(den2<0?-den2:den2); if(lhs<=rhs) continue; }
                            // s = Minv (a + si t, b + 1/2), common denominator D*den2
                            ll ui = a*den2 + si*N2, um = (2*b+1)*den;   // (b+1/2)*den2 = (2b+1) den
                            ll X = (ll)nr[m]*ui - (ll)nr[i]*um, Y = -(ll)ns[m]*ui + (ll)ns[i]*um;
                            consider(X, Y, D*den2);
                        }
                    }
                }
            }
        }
        printf("%lld %lld %lld %lld %lld\n", bp, bq, bX, bY, bDen);
    }
    return 0;
}
