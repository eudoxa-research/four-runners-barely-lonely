// enum25.c -- Proposition 9.14 of "Four runners that are barely lonely".
// Enumerates all primitive rank-2 sublattices of Z^4 (row Hermite normal form bases) with covolume^2 <= A2 that are
// not contained in a coordinate hyperplane. Lattices contained in a special 3-torus (characters with |m|_1 = 3) or in a
// 3-torus W_m with |m|_1 = 5 are counted and skipped. For the others: if some grid point (i/Q, j/Q), Q in QL[], has
// G >= THR (non-strict), the lattice is discarded; otherwise the exact maximizer (the algorithm of torusml2.c) is run,
// and the lattice is discarded if its maximizer has G >= THR (the maximizer is an exact certificate). The remaining
// lattices (ML < THR) are printed as "s0 r0 s1 r1 s2 r2 s3 r3 p q X Y Den" with ML = p/q attained at (X/Den, Y/Den).
// Usage: ./enum25 A2 thr_num thr_den [njobs job]
// Proposition 9.14: ./enum25 11331 2 5 2 0 > v_0.txt ; ./enum25 11331 2 5 2 1 > v_1.txt ; cat v_0.txt v_1.txt | sort > surv25.txt
// Expected (per job, two jobs): 789460684 lattices in total, 10650528 special, 18416448 in |m|_1 = 5 tori,
// 22410360 discarded by the exact maximizer, 9480 survivors.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
typedef long long ll;
typedef __int128 i128;
static ll gcdll(ll a, ll b){ if(a<0)a=-a; if(b<0)b=-b; while(b){ll t=a%b;a=b;b=t;} return a; }
static ll mod(ll a, ll m){ ll r=a%m; if(r<0) r+=m; return r; }

static ll A2; static ll thr_num, thr_den; static int nonstrict=1; static int countonly; static int njobs=1, job=0;
static ll total=0, survivors=0;

// quick certificate: is there a grid point (x,y) = (i/Q, j/Q) with min_k || s_k x + r_k y || >= THR ?
static int grid_cert(const int *s, const int *r, int Q){
    // value at (i,j): for each k, z = (s_k i + r_k j) mod Q, dist = min(z,Q-z)/Q >= thr  <=> dist*thr_den >= thr_num*Q
    for(int i=0;i<Q;i++) for(int j=0;j<Q;j++){
        int ok=1;
        for(int k=0;k<4;k++){
            ll z = mod((ll)s[k]*i + (ll)r[k]*j, Q);
            if(Q-z<z) z=Q-z;
            if(nonstrict ? (z*thr_den < thr_num*Q) : (z*thr_den <= thr_num*Q)){ ok=0; break; }
        }
        if(ok) return 1;
    }
    return 0;
}


// special characters: x_i = 2 x_j  (m = e_i - 2 e_j, all signs/positions) and x_i = x_j + x_k (m = e_i - e_j - e_k)
static int nspec=0; static int spec[128][4];
static void build_spec(void){
    for(int i=0;i<4;i++) for(int j=0;j<4;j++){ if(i==j) continue;
        for(int sg=-1;sg<=1;sg+=2){ int m[4]={0,0,0,0}; m[i]=1; m[j]=2*sg; for(int k=0;k<4;k++) spec[nspec][k]=m[k]; nspec++; } }
    for(int i=0;i<4;i++) for(int j=0;j<4;j++) for(int k=j+1;k<4;k++){ if(j==i||k==i) continue;
        for(int s1=-1;s1<=1;s1+=2) for(int s2=-1;s2<=1;s2+=2){ int m[4]={0,0,0,0}; m[i]=1; m[j]=s1; m[k]=s2; for(int t=0;t<4;t++) spec[nspec][t]=m[t]; nspec++; } }
}
static int in_special(const int *s, const int *r){
    for(int q=0;q<nspec;q++){ long a=0,b=0; for(int k=0;k<4;k++){ a+=(long)spec[q][k]*s[k]; b+=(long)spec[q][k]*r[k]; } if(a==0&&b==0) return 1; }
    return 0;
}

static ll fl(ll a, ll b){ ll q=a/b; if((a%b)!=0 && ((a<0)!=(b<0))) q--; return q; }
static int ns[4], nr[4];
static ll bp, bq, bX, bY, bDen;
// evaluate G at (X/Den, Y/Den) and update best
static void consider(ll X, ll Y, ll Den){
    if(Den<0){ Den=-Den; X=-X; Y=-Y; }
    X=mod(X,Den); Y=mod(Y,Den);
    ll best=Den;
    for(int i=0;i<4;i++){ ll z=mod((ll)ns[i]*X+(ll)nr[i]*Y, Den); if(Den-z<z) z=Den-z; if(z<best) best=z; }
    if((i128)best*bq > (i128)bp*Den){ ll g=gcdll(best,Den); bp=best/g; bq=Den/g; bX=X; bY=Y; bDen=Den; }
}
// fundamental domain reps of Z^2 / L, L generated by columns (Si,Sj),(Ri,Rj) of M=[[Si,Ri],[Sj,Rj]] (rows = forms)
// returns g1,g2 such that reps are (a,b), 0<=a<g1, 0<=b<g2 ; valid because L = <(g1,c),(0,g2)>.
static void hnf2(ll Si, ll Ri, ll Sj, ll Rj, ll *g1, ll *g2){
    ll D = Si*Rj - Ri*Sj; ll a=gcdll(Si,Ri); *g1=a; *g2 = (D<0?-D:D)/a;
}
static void exact_ml(const int *s, const int *r){
 for(int k=0;k<4;k++){ns[k]=s[k]; nr[k]=r[k];}
 bp=0; bq=1; bX=0; bY=0; bDen=1;
        // (c) two independent forms at half-integers: l_i = a + 1/2, l_j = b + 1/2
        for(int i=0;i<4;i++) for(int j=i+1;j<4;j++){
            ll D=(ll)ns[i]*nr[j]-(ll)nr[i]*ns[j]; if(D==0) continue;
            ll g1,g2; hnf2(ns[i],nr[i],ns[j],nr[j],&g1,&g2);
            for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                // solve [[Si,Ri],[Sj,Rj]] (x,y) = (a+1/2, b+1/2) -> over 2D
                ll ui=2*a+1, uj=2*b+1;
                ll X = ui*nr[j] - uj*nr[i], Y = ns[i]*uj - ns[j]*ui; consider(X, Y, 2*D);
            }
        }
        // (a) base pair (i,j) independent, third m, signs: l_i = a + si t, l_j = b + sj t, l_m = k + sm t, t in (0,1/2]
        for(int i=0;i<4;i++) for(int j=i+1;j<4;j++) for(int m=0;m<4;m++){
            if(m==i||m==j) continue;
            // use each unordered triple once: require that (i,j) is the first independent pair of the sorted triple
            int tr[3]={i,j,m}; // sort
            for(int x=0;x<3;x++) for(int y=x+1;y<3;y++) if(tr[y]<tr[x]){int t=tr[x];tr[x]=tr[y];tr[y]=t;}
            int fi=-1,fj=-1;
            for(int x=0;x<3 && fi<0;x++) for(int y=x+1;y<3;y++){ ll d=(ll)ns[tr[x]]*nr[tr[y]]-(ll)nr[tr[x]]*ns[tr[y]]; if(d!=0){fi=tr[x];fj=tr[y];break;} }
            if(fi!=i || fj!=j) continue;
            ll D=(ll)ns[i]*nr[j]-(ll)nr[i]*ns[j];
            ll g1,g2; hnf2(ns[i],nr[i],ns[j],nr[j],&g1,&g2);
            for(int si=-1;si<=1;si+=2) for(int sj=-1;sj<=1;sj+=2) for(int sm=-1;sm<=1;sm+=2){
                // s(t) = Minv (a + si t, b + sj t); Minv = (1/D) [[Rj, -Ri],[-Sj, Si]]
                // l_m(s) = (1/D) [ (Sm Rj - Rm Sj)(a + si t) + (-Sm Ri + Rm Si)(b + sj t) ] = (P0 + t Q0)/D
                ll cA = (ll)ns[m]*nr[j] - (ll)nr[m]*ns[j], cB = -(ll)ns[m]*nr[i] + (ll)nr[m]*ns[i];
                ll Q0 = cA*si + cB*sj;          // l_m slope numerator (over D)
                ll den = Q0 - (ll)sm*D;         // equation: (P0 + t Q0)/D = k + sm t  ->  t (Q0 - sm D) = k D - P0
                if(den==0) continue;
                for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                    ll P0 = cA*a + cB*b;
                    // t = (k D - P0)/den in (0, 1/2]  ->  k D - P0 in (0, den/2] (den>0) or [den/2, 0) (den<0)
                    ll lo, hi; // range for N = k*D - P0 (scaled by 2 for the half)
                    // solve for k: if den>0: 0 < kD - P0 <= den/2 ; if den<0: den/2 <= kD - P0 < 0
                    ll A_, B_; // N in (A_, B_] in units of 1/2: use 2N
                    if(den>0){ A_=0; B_=den; } else { A_=den; B_=0; }  // 2N in (A_*?, ...]: handle below
                    // 2(kD - P0) in (0, den] if den>0 ; in [den, 0) if den<0
                    ll Dabs = D>0?D:-D;
                    // iterate k over the range: kD in (P0, P0 + den/2] or [P0 + den/2, P0)
                    ll L2 = 2*P0 + (den>0?0:den), H2 = 2*P0 + (den>0?den:0); // 2kD in (L2,H2] or [L2,H2)
                    ll kmin, kmax;
                    if(D>0){ kmin = fl(L2, 2*D) - 1; kmax = fl(H2, 2*D) + 1; } else { kmin = fl(-H2, -2*D) - 1; kmax = fl(-L2, -2*D) + 1; }
                    (void)lo;(void)hi;(void)A_;(void)B_;(void)Dabs;
                    for(ll k=kmin;k<=kmax;k++){
                        ll N = k*D - P0;
                        // check t = N/den in (0, 1/2]
                        if(den>0){ if(!(N>0 && 2*N<=den)) continue; } else { if(!(N<0 && 2*N>=den)) continue; }
                        // prune: t <= current best cannot improve (G(s) <= t on active forms)
                        // t = N/den ; compare N/den <= bp/bq
                        { i128 lhs=(i128)(N<0?-N:N)*bq, rhs=(i128)bp*(den<0?-den:den); if(lhs<=rhs) continue; }
                        // s = Minv (a + si t, b + sj t) with t = N/den: common denominator D*den
                        ll ui = a*den + si*N, uj = b*den + sj*N;   // (a + si t)*den
                        ll X = (ll)nr[j]*ui - (ll)nr[i]*uj, Y = -(ll)ns[j]*ui + (ll)ns[i]*uj;
                        consider(X, Y, D*den);
                    }
                }
            }
        }
        // (b) proportional pair (i,j) at common level, third m at half-integer; base pair (i,m) independent
        for(int i=0;i<4;i++) for(int j=0;j<4;j++){
            if(i==j) continue;
            if((ll)ns[i]*nr[j] != (ll)ns[j]*nr[i]) continue;
            if(i>j) continue;
            for(int m=0;m<4;m++){ if(m==i||m==j) continue;
                ll D=(ll)ns[i]*nr[m]-(ll)nr[i]*ns[m]; if(D==0) continue;
                ll g1,g2; hnf2(ns[i],nr[i],ns[m],nr[m],&g1,&g2);
                for(int si=-1;si<=1;si+=2) for(int sj=-1;sj<=1;sj+=2){
                    // l_i = a + si t, l_m = b + 1/2 ; l_j(s) = (cA (a + si t) + cB (b + 1/2))/D ; equation l_j = k + sj t
                    ll cA = (ll)ns[j]*nr[m] - (ll)nr[j]*ns[m], cB = -(ll)ns[j]*nr[i] + (ll)nr[j]*ns[i];
                    ll Q0 = cA*si; ll den = Q0 - (ll)sj*D; if(den==0) continue;
                    for(ll a=0;a<g1;a++) for(ll b=0;b<g2;b++){
                        // 2 P0 = 2 cA a + cB (2b+1)
                        ll P2 = 2*cA*a + cB*(2*b+1);
                        // t = (k D - P0)/den = (2kD - P2)/(2 den)
                        ll den2=2*den;
                        ll L2 = P2 + (den2>0?0:den2/2*1), H2 = P2 + (den2>0?den2/2:0);
                        // 2kD in (P2, P2 + den] or [P2 + den, P2)
                        ll lo2 = (den>0)? P2 : P2+den, hi2 = (den>0)? P2+den : P2;
                        ll kmin, kmax;
                        if(D>0){ kmin=fl(lo2,2*D)-1; kmax=fl(hi2,2*D)+1; } else { kmin=fl(-hi2,-2*D)-1; kmax=fl(-lo2,-2*D)+1; }
                        (void)L2;(void)H2;
                        for(ll k=kmin;k<=kmax;k++){
                            ll N2 = 2*k*D - P2; // t = N2/den2
                            if(den2>0){ if(!(N2>0 && 2*N2<=den2)) continue; } else { if(!(N2<0 && 2*N2>=den2)) continue; }
                            { i128 lhs=(i128)(N2<0?-N2:N2)*bq, rhs=(i128)bp*(den2<0?-den2:den2); if(lhs<=rhs) continue; }
                            // s = Minv (a + si t, b + 1/2), common denominator D*den2
                            ll ui = a*den2 + si*N2, um = (2*b+1)*den;   // (b+1/2)*den2 = (2b+1) den
                            ll X = (ll)nr[m]*ui - (ll)nr[i]*um, Y = -(ll)ns[m]*ui + (ll)ns[i]*um;
                            consider(X, Y, D*den2);
                        }
                    }
                }
            }
        }
        }

static ll skipped_special=0;
static int nfive=0; static int five[256][4];
static void build_five(void){
    int m[4];
    for(m[0]=-5;m[0]<=5;m[0]++) for(m[1]=-5;m[1]<=5;m[1]++) for(m[2]=-5;m[2]<=5;m[2]++) for(m[3]=-5;m[3]<=5;m[3]++){
        int l1=abs(m[0])+abs(m[1])+abs(m[2])+abs(m[3]); if(l1!=5) continue;
        ll g=0; for(int k=0;k<4;k++) g=gcdll(g,m[k]); if(g!=1) continue;
        // keep one of +-m: first nonzero entry positive
        int f=0; while(m[f]==0) f++; if(m[f]<0) continue;
        for(int k=0;k<4;k++) five[nfive][k]=m[k]; nfive++; }
}
static int in_five(const int *s, const int *r){
    for(int q=0;q<nfive;q++){ long a=0; for(int k=0;k<4;k++) a+=(long)five[q][k]*s[k]; if(a) continue; long b=0; for(int k=0;k<4;k++) b+=(long)five[q][k]*r[k]; if(b==0) return 1; }
    return 0;
}
static ll skipped_five=0;

static const int QL[]={2,10,20,30,0}; static ll exact_disc=0;
#include <time.h>
static time_t t0;
static void process(const int *s, const int *r){
    total++;
    if((total % 200000000LL)==0){ fprintf(stderr,"progress: %lld lattices, %ld s, survivors %lld\n", total, (long)(time(NULL)-t0), survivors); fflush(stderr); }
    if((total % njobs) != job) return;
    if(in_special(s,r)){ skipped_special++; return; }
    if(in_five(s,r)){ skipped_five++; return; }
    for(int t=0; QL[t]; t++) if(grid_cert(s,r,QL[t])) return;
    exact_ml(s,r);
    // discard iff bp/bq >= thr ; the maximizer (bX/bDen, bY/bDen) is an exact certificate
    if((i128)bp*thr_den >= (i128)thr_num*bq){ exact_disc++; return; }
    survivors++;
    printf("%d %d %d %d %d %d %d %d %lld %lld %lld %lld %lld\n", s[0],r[0],s[1],r[1],s[2],r[2],s[3],r[3], bp,bq,bX,bY,bDen);
}
int main(int argc, char **argv){
    A2 = atoll(argv[1]); ll A = (ll)floor(sqrt((double)A2))+1;
    thr_num = atoll(argv[2]); thr_den = atoll(argv[3]);
    setvbuf(stdout, NULL, _IOLBF, 0); t0=time(NULL);
    njobs = argc>4 ? atoi(argv[4]) : 1; job = argc>5 ? atoi(argv[5]) : 0; countonly = 0; build_spec(); build_five(); fprintf(stderr,"nspec=%d nfive=%d\n",nspec,nfive);
    int s[4], r[4];
    for(int p=0;p<4;p++) for(int q=p+1;q<4;q++){
        for(int i=0;i<4;i++){ s[i]=0; r[i]=0; }
        for(ll a=1; a*a<=A2; a++){
            for(ll b=1; a*a*b*b<=A2; b++){
                ll rem0 = A2 - a*a*b*b;
                // columns: p (s=a, r=0), q (s=sq in [0,b), r=b), middle columns j in (p,q): s_j free, r_j=0;
                // columns j>q: s_j, r_j free.
                int mids[4], nm=0, highs[4], nh=0;
                for(int j=p+1;j<q;j++) mids[nm++]=j;
                for(int j=q+1;j<4;j++) highs[nh++]=j;
                for(ll sq=0; sq<b; sq++){
                    // middle columns: minor p_{jq} = s_j*b, p_{pj}=0 -> |s_j| <= sqrt(rem)/b
                    // enumerate middle s_j
                    ll smid[2]={0,0};
                    ll lim_mid = (ll)floor(sqrt((double)rem0)/b)+1;
                    // nested loops up to nm=2
                    ll m0lo = nm>0 ? -lim_mid : 0, m0hi = nm>0 ? lim_mid : 0;
                    for(ll m0=m0lo; m0<=m0hi; m0++){
                        ll rem1 = rem0 - (nm>0 ? m0*m0*b*b : 0); if(rem1<0) continue;
                        ll m1lo = nm>1 ? -lim_mid : 0, m1hi = nm>1 ? lim_mid : 0;
                        for(ll m1=m1lo; m1<=m1hi; m1++){
                            ll rem2 = rem1 - (nm>1 ? m1*m1*b*b : 0); if(rem2<0) continue;
                            smid[0]=m0; smid[1]=m1;
                            // high columns: for each j>q: p_{pj} = a*r_j, p_{qj} = sq*r_j - s_j*b, p_{mj} = s_m*r_j (for middle m)
                            // enumerate r_j and s_j for the high columns (nh <= 2)
                            ll lim_r = (ll)floor(sqrt((double)rem2)/a)+1;
                            ll h0rlo = nh>0 ? -lim_r : 0, h0rhi = nh>0 ? lim_r : 0;
                            for(ll r0=h0rlo; r0<=h0rhi; r0++){
                                ll c0 = (nh>0) ? (a*a*r0*r0 + (nm>0? smid[0]*smid[0]*r0*r0:0) + (nm>1? smid[1]*smid[1]*r0*r0:0)) : 0;
                                ll rem3 = rem2 - c0; if(rem3<0) continue;
                                // s_j0: p_{qj} = sq*r0 - s*b, need (sq*r0 - s*b)^2 <= rem3
                                ll s0lo=0, s0hi=0;
                                if(nh>0){ double sr=sqrt((double)rem3); s0lo=(ll)ceil((sq*r0 - sr)/b)-1; s0hi=(ll)floor((sq*r0 + sr)/b)+1; }
                                for(ll s0=s0lo; s0<=s0hi; s0++){
                                    ll pq0 = nh>0 ? (sq*r0 - s0*b) : 0;
                                    ll rem4 = rem3 - pq0*pq0; if(rem4<0) continue;
                                    ll lim_r1 = (ll)floor(sqrt((double)rem4)/a)+1;
                                    ll h1rlo = nh>1 ? -lim_r1 : 0, h1rhi = nh>1 ? lim_r1 : 0;
                                    for(ll r1=h1rlo; r1<=h1rhi; r1++){
                                        ll c1 = nh>1 ? (a*a*r1*r1 + (nm>0? smid[0]*smid[0]*r1*r1:0) + (nm>1? smid[1]*smid[1]*r1*r1:0)) : 0;
                                        ll rem5 = rem4 - c1; if(rem5<0) continue;
                                        ll s1lo=0, s1hi=0;
                                        if(nh>1){ double sr=sqrt((double)rem5); s1lo=(ll)ceil((sq*r1 - sr)/b)-1; s1hi=(ll)floor((sq*r1 + sr)/b)+1; }
                                        for(ll s1=s1lo; s1<=s1hi; s1++){
                                            ll pq1 = nh>1 ? (sq*r1 - s1*b) : 0;
                                            ll rem6 = rem5 - pq1*pq1; if(rem6<0) continue;
                                            // minor between the two high columns: s0*r1 - s1*r0
                                            ll phh = nh>1 ? (s0*r1 - s1*r0) : 0;
                                            if(phh*phh > rem6) continue;
                                            // assemble
                                            for(int i=0;i<4;i++){ s[i]=0; r[i]=0; }
                                            s[p]=(int)a; s[q]=(int)sq; r[q]=(int)b;
                                            if(nm>0) s[mids[0]]=(int)smid[0];
                                            if(nm>1) s[mids[1]]=(int)smid[1];
                                            if(nh>0){ s[highs[0]]=(int)s0; r[highs[0]]=(int)r0; }
                                            if(nh>1){ s[highs[1]]=(int)s1; r[highs[1]]=(int)r1; }
                                            // primitivity: gcd of all minors == 1 ; coordinate-free
                                            ll g=0; int cf=1;
                                            for(int i=0;i<4;i++){ if(s[i]==0 && r[i]==0) cf=0; }
                                            if(!cf) continue;
                                            for(int i=0;i<4;i++) for(int j=i+1;j<4;j++){ ll mnr=(ll)s[i]*r[j]-(ll)s[j]*r[i]; g=gcdll(g,mnr); }
                                            if(g!=1) continue;
                                            process(s,r);
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
    fprintf(stderr,"job %d/%d: total lattices (covol^2<=%lld, primitive, coord-free): %lld ; inside special 3-tori (this job): %lld ; inside |m|_1=5 tori (this job): %lld ; discarded by exact maximizer: %lld ; survivors: %lld\n", job, njobs, A2, total, skipped_special, skipped_five, exact_disc, survivors);
    return 0;
}
